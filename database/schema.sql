-- Comparación sin acentos ni mayúsculas (sin depender de extensiones)
CREATE OR REPLACE FUNCTION sin_acentos(t text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
$$ SELECT translate(lower(coalesce(t, '')), 'áéíóúüñàèìòùâêîôûäëïö', 'aeiouunaeiouaeiouaeio') $$;

-- LEFT(fecha, n) como en MySQL: devuelve el texto 'AAAA-MM-DD HH:MM:SS' recortado
CREATE OR REPLACE FUNCTION left(t timestamp, n integer) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$ SELECT pg_catalog.left(t::text, n) $$;
CREATE OR REPLACE FUNCTION left(t date, n integer) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$ SELECT pg_catalog.left(t::text, n) $$;

-- ---------- Cuentas ----------
CREATE TABLE IF NOT EXISTS usuarios (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo             VARCHAR(12)  NOT NULL CHECK (tipo IN ('adoptante','refugio','admin','funcionario')),
  nombre           VARCHAR(120) NOT NULL,
  correo           VARCHAR(254) NOT NULL,
  hash             VARCHAR(100) NOT NULL,
  estado           VARCHAR(10)  NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','pendiente','rechazada','baja','eliminada')),
  aviso_version    VARCHAR(10)  NOT NULL,
  aviso_fecha      TIMESTAMP(0) NOT NULL,
  creado           TIMESTAMP(0) NOT NULL,
  verificado_en    TIMESTAMP(0) NULL,
  rechazado_en     TIMESTAMP(0) NULL,
  baja_en          TIMESTAMP(0) NULL,
  purgar_en        TIMESTAMP(0) NULL,
  purgado          SMALLINT     NOT NULL DEFAULT 0,
  eliminado_motivo VARCHAR(300) NULL,
  eliminado_en     TIMESTAMP(0) NULL,
  telefono         CHAR(10)     NULL,          -- del adoptante: el refugio lo ve en sus solicitudes
  mayor_edad_en    TIMESTAMP(0) NULL,          -- declaró ser mayor de 18 años (requisito para adoptar)
  avatar_v         INTEGER      NOT NULL DEFAULT 0  -- versión de la foto de perfil (0 = sin foto)
);
-- Correo y teléfono únicos solo entre cuentas vigentes: tras darse de baja se pueden volver a usar
CREATE UNIQUE INDEX IF NOT EXISTS uq_correo_vigente ON usuarios (lower(correo)) WHERE estado NOT IN ('baja','eliminada');
CREATE UNIQUE INDEX IF NOT EXISTS uq_telefono_vigente ON usuarios (telefono) WHERE telefono IS NOT NULL AND estado NOT IN ('baja','eliminada');
-- Solo puede existir UN administrador. Para cambiarlo hay que hacerlo directamente en la base (npm run admin).
CREATE UNIQUE INDEX IF NOT EXISTS uq_un_admin ON usuarios (tipo) WHERE tipo = 'admin';
CREATE INDEX IF NOT EXISTS ix_usuarios_tipo_estado ON usuarios (tipo, estado);

CREATE TABLE IF NOT EXISTS avatares (
  usuario_id  INTEGER PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
  tipo        VARCHAR(20) NOT NULL,
  datos       BYTEA       NOT NULL,
  creado_en   TIMESTAMP(0) NOT NULL
);

CREATE TABLE IF NOT EXISTS catalogo_valores (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  catalogo  VARCHAR(20) NOT NULL CHECK (catalogo IN ('tamano','edad','tipo_requisito','alcaldia','vacuna','documento')),
  nombre    VARCHAR(50) NOT NULL,
  orden     INTEGER  NOT NULL DEFAULT 0,
  activo    SMALLINT NOT NULL DEFAULT 1,
  UNIQUE (catalogo, nombre)
);

CREATE TABLE IF NOT EXISTS refugios (
  usuario_id   INTEGER PRIMARY KEY REFERENCES usuarios(id),
  institucion  VARCHAR(120) NOT NULL,
  direccion    VARCHAR(200) NOT NULL,       -- texto armado con los campos de abajo (para mostrar)
  calle        VARCHAR(100) NULL,
  num_ext      VARCHAR(10)  NULL,
  num_int      VARCHAR(10)  NULL,
  colonia      VARCHAR(80)  NULL,
  cp           CHAR(5)      NULL,
  telefono     CHAR(10)     NOT NULL,
  alcaldia_id  INTEGER NULL REFERENCES catalogo_valores(id),
  lat          NUMERIC(9,6) NULL,          -- coordenadas de Google (opcional)
  lng          NUMERIC(9,6) NULL,
  place_id     VARCHAR(300) NULL
);

-- dia: 0 = lunes … 6 = domingo
CREATE TABLE IF NOT EXISTS refugio_horarios (
  refugio_id  INTEGER  NOT NULL REFERENCES refugios(usuario_id),
  dia         SMALLINT NOT NULL,
  cerrado     SMALLINT NOT NULL DEFAULT 1,
  abre        CHAR(5) NULL,
  cierra      CHAR(5) NULL,
  PRIMARY KEY (refugio_id, dia)
);

-- Cambios de datos sensibles del refugio (nombre, dirección, teléfono, horario): esperan aprobación del admin
CREATE TABLE IF NOT EXISTS refugio_cambios (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  refugio_id  INTEGER NOT NULL REFERENCES refugios(usuario_id),
  datos       JSONB   NOT NULL,             -- solo los campos que cambian, con su valor nuevo
  anteriores  JSONB   NOT NULL,             -- valores vigentes al momento de pedirlo
  estado      VARCHAR(10) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobado','rechazado','cancelado')),
  motivo      VARCHAR(300) NULL,
  revisor_id  INTEGER NULL REFERENCES usuarios(id),
  creado_en   TIMESTAMP(0) NOT NULL,
  revisado_en TIMESTAMP(0) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_un_cambio_pendiente ON refugio_cambios (refugio_id) WHERE estado = 'pendiente';

-- ---------- Publicaciones ----------
CREATE TABLE IF NOT EXISTS animales (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  refugio_id           INTEGER NOT NULL REFERENCES refugios(usuario_id),
  nombre               VARCHAR(50)  NOT NULL,
  raza                 VARCHAR(40)  NOT NULL,           -- id de raza o 'mestizo'
  raza_aprox           VARCHAR(40)  NULL,               -- solo mestizos: raza a la que más se parece
  edad_id              INTEGER NOT NULL REFERENCES catalogo_valores(id),
  tamano_id            INTEGER NOT NULL REFERENCES catalogo_valores(id),
  salud                VARCHAR(500) NOT NULL DEFAULT '',
  temperamento         VARCHAR(300) NOT NULL DEFAULT '',
  salud_general        VARCHAR(20) NULL,                   -- opciones cerradas (server/util.js → OPCIONES_ANIMAL)
  tratamiento          VARCHAR(20) NULL,
  temp_general         VARCHAR(20) NULL,
  temp_perros          VARCHAR(20) NULL,
  temp_desconocidos    VARCHAR(20) NULL,
  temp_comida          VARCHAR(20) NULL,
  fecha_ingreso        DATE NOT NULL,
  esterilizado         SMALLINT NOT NULL DEFAULT 0,
  fecha_esterilizacion DATE NULL,
  desparasitado        SMALLINT NOT NULL DEFAULT 0,       -- protocolo CDMX: se entrega desparasitado
  peso_kg              NUMERIC(4,1) NULL,
  altura_cm            SMALLINT NULL,
  estado               VARCHAR(12) NOT NULL DEFAULT 'disponible' CHECK (estado IN ('disponible','adoptado')),
  adoptado_en          DATE NULL,
  eliminado            SMALLINT NOT NULL DEFAULT 0,
  eliminado_por        VARCHAR(12) NULL CHECK (eliminado_por IN ('refugio','admin','funcionario')),
  eliminado_motivo     VARCHAR(40)  NULL,
  eliminado_desc       VARCHAR(300) NULL,
  eliminado_en         TIMESTAMP(0) NULL,
  publicado_en         TIMESTAMP(0) NOT NULL,
  actualizado_en       TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_animales_catalogo ON animales (eliminado, estado, publicado_en);
CREATE INDEX IF NOT EXISTS ix_animales_refugio ON animales (refugio_id);

CREATE TABLE IF NOT EXISTS requisitos (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id  INTEGER NOT NULL REFERENCES animales(id) ON DELETE CASCADE,
  nombre     VARCHAR(100) NOT NULL,
  tipo_id    INTEGER NOT NULL REFERENCES catalogo_valores(id),
  otro       SMALLINT NOT NULL DEFAULT 0   -- 1 = escrito por el refugio (fuera de la lista de documentos)
);

CREATE TABLE IF NOT EXISTS vacunas (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id  INTEGER NOT NULL REFERENCES animales(id) ON DELETE CASCADE,
  nombre     VARCHAR(60) NOT NULL,
  fecha      DATE NOT NULL
);

-- ---------- Solicitudes (protocolo de adopción) ----------
CREATE TABLE IF NOT EXISTS solicitudes (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id      INTEGER NOT NULL REFERENCES animales(id),
  adoptante_id   INTEGER NOT NULL REFERENCES usuarios(id),
  estado         VARCHAR(10) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobada','rechazada','cancelada')),
  motivo_rechazo VARCHAR(300) NULL,
  cuestionario   JSONB NULL,                 -- formato de adopción (vivienda, convivencia, experiencia, compromiso)
  compromiso_en  TIMESTAMP(0) NULL,          -- aceptó la carta compromiso (Ley de Protección a los Animales CDMX, art. 32)
  enviada_en     TIMESTAMP(0) NOT NULL,
  aprobada_en    TIMESTAMP(0) NULL,
  rechazada_en   TIMESTAMP(0) NULL,
  visita         VARCHAR(12) NULL CHECK (visita IN ('realizada','no_requerida','no_apta')),   -- visita domiciliaria
  visita_en      DATE NULL,
  concretada_en  DATE NULL,
  entrega        JSONB NULL                  -- lista de entrega: esterilizado, vacunas, desparasitado, carta firmada, folio RUAC
);
CREATE INDEX IF NOT EXISTS ix_sol_animal_estado ON solicitudes (animal_id, estado);
CREATE INDEX IF NOT EXISTS ix_sol_adoptante_estado ON solicitudes (adoptante_id, estado);

-- Conversación corta adoptante ↔ refugio dentro de cada solicitud
CREATE TABLE IF NOT EXISTS mensajes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id  INTEGER NOT NULL REFERENCES solicitudes(id) ON DELETE CASCADE,
  autor_id      INTEGER NOT NULL REFERENCES usuarios(id),
  texto         VARCHAR(500) NOT NULL,
  creado_en     TIMESTAMP(0) NOT NULL,
  leido_en      TIMESTAMP(0) NULL
);
CREATE INDEX IF NOT EXISTS ix_mensajes_solicitud ON mensajes (solicitud_id, creado_en);

CREATE TABLE IF NOT EXISTS citas (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id  INTEGER NOT NULL UNIQUE REFERENCES solicitudes(id),
  refugio_id    INTEGER NOT NULL REFERENCES refugios(usuario_id),
  fecha         DATE NOT NULL,
  hora          CHAR(5) NOT NULL,
  creada_en     TIMESTAMP(0) NOT NULL,
  UNIQUE (refugio_id, fecha, hora)
);

-- Seguimiento posterior a la adopción (1 semana, 1 mes y 3 meses después de la entrega)
CREATE TABLE IF NOT EXISTS seguimientos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id  INTEGER NOT NULL REFERENCES solicitudes(id) ON DELETE CASCADE,
  etapa         VARCHAR(10) NOT NULL CHECK (etapa IN ('1_semana','1_mes','3_meses')),
  programado    DATE NOT NULL,
  realizado_en  DATE NULL,
  resultado     VARCHAR(12) NULL CHECK (resultado IN ('bien','con_dudas','problema','sin_contacto')),
  notas         VARCHAR(300) NULL,
  avisado       SMALLINT NOT NULL DEFAULT 0,   -- ya se notificó al refugio que toca hacerlo
  UNIQUE (solicitud_id, etapa)
);

-- ---------- Notificaciones ----------
CREATE TABLE IF NOT EXISTS notificaciones (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id),
  texto       VARCHAR(200) NOT NULL,
  enlace      VARCHAR(200) NULL,            -- ruta de la página a la que lleva (ej. #/solicitudes?id=12)
  leida       SMALLINT NOT NULL DEFAULT 0,
  creada_en   TIMESTAMP(0) NOT NULL,
  leida_en    TIMESTAMP(0) NULL
);
CREATE INDEX IF NOT EXISTS ix_notif_usuario ON notificaciones (usuario_id, leida, creada_en);

CREATE TABLE IF NOT EXISTS errores_notificacion (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL,
  texto       VARCHAR(200) NOT NULL,
  detalle     VARCHAR(300) NOT NULL,
  creado_en   TIMESTAMP(0) NOT NULL,
  revisado    SMALLINT NOT NULL DEFAULT 0
);

-- ---------- Reportes ----------
-- Adoptantes reportan fichas y refugios; los refugios reportan adoptantes
CREATE TABLE IF NOT EXISTS reportes (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  autor_id       INTEGER NOT NULL REFERENCES usuarios(id),
  objetivo_tipo  VARCHAR(10) NOT NULL CHECK (objetivo_tipo IN ('animal','refugio','usuario')),
  objetivo_id    INTEGER NOT NULL,
  motivo         VARCHAR(40) NOT NULL,
  descripcion    VARCHAR(300) NOT NULL,
  estado         VARCHAR(10) NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto','resuelto','descartado')),
  nota           VARCHAR(300) NULL,
  admin_id       INTEGER NULL,
  creado_en      TIMESTAMP(0) NOT NULL,
  cerrado_en     TIMESTAMP(0) NULL
);
CREATE INDEX IF NOT EXISTS ix_reportes_estado ON reportes (estado, creado_en);

-- ---------- Sesiones y recuperación ----------
CREATE TABLE IF NOT EXISTS sesiones (
  token_hash        CHAR(64) PRIMARY KEY,
  usuario_id        INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  creada_en         TIMESTAMP(0) NOT NULL,
  ultima_actividad  TIMESTAMP(0) NOT NULL,
  ip                VARCHAR(45) NULL
);
CREATE INDEX IF NOT EXISTS ix_sesiones_usuario ON sesiones (usuario_id);

CREATE TABLE IF NOT EXISTS recuperaciones (
  token_hash  CHAR(64) PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_en   TIMESTAMP(0) NOT NULL,
  usado_en    TIMESTAMP(0) NULL
);

-- Cuenta las solicitudes de enlace por correo (exista o no la cuenta) para el límite de 3 por hora
CREATE TABLE IF NOT EXISTS recuperacion_intentos (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo    VARCHAR(254) NOT NULL,
  creado_en TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_recup_correo ON recuperacion_intentos (correo, creado_en);

